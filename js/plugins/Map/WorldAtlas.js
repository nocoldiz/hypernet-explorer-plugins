/*:
 * @target MZ
 * @plugindesc World Atlas: the political map of the world, drawn as SVG from WorldGen/Countries.json
 * @author Omni-Lex
 *
 * @command openAtlas
 * @text Open World Atlas
 * @desc Opens the political atlas of the world.
 *
 * @help WorldAtlas.js
 *
 * The atlas every nation in js/db/WorldGen/Countries.json is painted on. It is
 * NOT the travel map (Map/WorldMap.js): nothing here teleports anybody, it is
 * the reference sheet that says who holds what and what the weather does there.
 *
 * === The world it draws ===
 * Geometry lives in js/db/WorldGen/Atlas.json, generated by tools/atlas/
 * gen_atlas.py from Natural Earth 50m (public domain). Two layers:
 *   - "land": every coast still standing, drawn as unclaimed ground.
 *   - "shapes": one entry per country, drawn over the land and coloured by
 *     whoever holds it.
 *
 * The Americas are gone. What stands in their place is Canadafrica: Canada
 * fused to a second Africa-shaped landmass that carries the old United States
 * (Cascadia Protectorate, Free States of Midwest, Eastern Seaboard) across its
 * northern belt and the whole of South America below it. Chile runs the entire
 * east coast of that continent as one long ribbon, which is why its hyperpower
 * is called Long Chile.
 *
 * === Controls ===
 * Mouse:    drag to pan, wheel to zoom, hover to read, click to select.
 * Arrows/WASD: pan.  PageUp/PageDown: step through the nations.
 * OK: centre on the selected nation.  Shift: cycle the shading.
 * Cancel/Esc: close.
 *
 * === Opening it ===
 * Pause menu -> World Map -> Atlas, the plugin command above, or
 * window.WorldAtlas.open() from a script call.
 */

