    // An unlisted holder (a mod, a hyperpower added later) still needs an ink
    // of its own, and it must be the same ink every time the atlas opens.
    function hashedInk(name) {
        let h = 0;
        for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) | 0;
        const hue = Math.abs(h) % 360;
        return `hsl(${hue}, 34%, 52%)`;
    }

    function powerInk(name) {
        if (!name) return POWER_INK[NEUTRAL];
        return POWER_INK[name] || hashedInk(name);
    }

    // Who actually holds the ground: the controller when there is one, the
    // faction the nation belongs to otherwise.
    function holderOf(country) {
        const ctrl = country.controller;
        if (ctrl && ctrl !== NEUTRAL) return ctrl;
        const fac = country.faction;
        if (fac && fac !== NEUTRAL) return fac;
        return NEUTRAL;
    }

    // Temperature shading: cold blue to hot red along one ramp, shared by the
    // map and by the legend under it so the two cannot drift apart.
    function rampInk(t) {
        const k = Math.max(0, Math.min(1, t));
        return `hsl(${Math.round(220 - 220 * k)}, 55%, ${Math.round(62 - 28 * Math.abs(k - 0.5))}%)`;
    }

    // The current season's daytime high, over the range the country table
    // actually covers (-28 to 43).
    function climateInk(country, season) {
        const s = country.seasons && country.seasons[season];
        if (!s || typeof s.dayTemp !== "number") return POWER_INK[NEUTRAL];
        return rampInk((s.dayTemp + 28) / 71);
    }

    // ── names ───────────────────────────────────────────────────────────────

    const nationLabel = (id) => (window.WorldNames ? window.WorldNames.nation(id) : String(id || ""));
    const powerLabel = (id) => {
        if (!id) return "";
        return window.WorldNames ? window.WorldNames.power(id) : String(id);
    };
    const regionLabel = (region) => {
        const key = REGION_KEYS[region];
        return key ? T("Atlas.region." + key) : String(region || "");
    };
    const seasonLabel = (season) => T("Atlas.season." + season);

    function escHtml(str) {
        return String(str === undefined || str === null ? "" : str)
            .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;");
    }

    // ── world state ─────────────────────────────────────────────────────────

    function activeSeason() {
        try {
            if (typeof $gameWeather !== "undefined" && $gameWeather &&
                typeof $gameWeather.getSeason === "function") {
                const s = String($gameWeather.getSeason()).toLowerCase();
                if (SEASONS.indexOf(s) >= 0) return s;
            }
        } catch (e) { /* no weather yet: fall through */ }
        return SEASONS[0];
    }

    // The nation the party is standing in, as WeatherSystem worked it out.
    function partyCountryName() {
        try {
            if (typeof $gameWeather !== "undefined" && $gameWeather && $gameWeather.currentCountry) {
                return $gameWeather.currentCountry.country || null;
            }
            const id = (typeof $gameVariables !== "undefined" && $gameVariables)
                ? $gameVariables.value(86) : 0;
            const hit = countryList().find((c) => c.id === id);
            return hit ? hit.country : null;
        } catch (e) {
            return null;
        }
    }

    // Where the party stands, in atlas degrees, when that can be answered
    // exactly: the world map's own squares run through the affine fit baked
    // into Atlas.json. Anywhere else the party is placed by their country.
    function partyPoint() {
        const data = atlasData();
        const wm = window.WorldMapTransfer;
        if (!data || !data.worldTile || !wm) return null;
        try {
            if (!$gameMap || $gameMap.mapId() !== wm.worldMapId) {
                const pos = wm.currentWorldCoords && wm.currentWorldCoords();
                if (!pos) return null;
                return applyWorldTile(data.worldTile.matrix, pos.x, pos.y);
            }
            return applyWorldTile(data.worldTile.matrix, $gamePlayer.x, $gamePlayer.y);
        } catch (e) {
            return null;
        }
    }

    function applyWorldTile(m, x, y) {
        if (!Array.isArray(m) || m.length < 6) return null;
        return [m[0] * x + m[1] * y + m[2], m[3] * x + m[4] * y + m[5]];
    }

    // ── geometry, built once per session ────────────────────────────────────

    let _built = null;

    function buildGeometry() {
        if (_built) return _built;
        const data = atlasData();
        if (!data || !data.shapes) return null;

        const path = (rings) => {
            let d = "";
            for (let r = 0; r < rings.length; r++) {
                const ring = rings[r];
                for (let i = 0; i < ring.length; i++) {
                    d += (i ? "L" : "M") + ring[i][0] + " " + (-ring[i][1]);
                }
                d += "Z";
            }
            return d;
        };

        const bounds = (rings) => {
            let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
            rings.forEach((ring) => ring.forEach((p) => {
                if (p[0] < x0) x0 = p[0];
                if (p[0] > x1) x1 = p[0];
                if (p[1] < y0) y0 = p[1];
                if (p[1] > y1) y1 = p[1];
            }));
            return { w: x1 - x0, h: y1 - y0 };
        };

        const shapes = {};
        Object.keys(data.shapes).forEach((name) => {
            const rings = data.shapes[name];
            const b = bounds(rings);
            shapes[name] = { d: path(rings), size: Math.max(b.w, b.h) };
        });

        // The world before the Squishing, for everything that moved.
        const legacy = {};
        Object.keys(data.legacy || {}).forEach((name) => {
            const rings = data.legacy[name];
            const b = bounds(rings);
            legacy[name] = { d: path(rings), size: Math.max(b.w, b.h) };
        });

        _built = {
            land: Array.isArray(data.land) ? path(data.land) : "",
            americas: Array.isArray(data.americas) ? path(data.americas) : "",
            canadafrica: Array.isArray(data.canadafrica) ? path(data.canadafrica) : "",
            landMorph: data.landMorph || null,
            shapes,
            legacy,
            morph: data.morph || {},
            anchors: data.anchors || {},
            legacyAnchors: data.legacyAnchors || {},
            notes: data.notes || {},
            markers: data.markers || {},
            era: (data.meta && data.meta.era) || { legacyUntil: 1992, settledFrom: 1994 },
        };
        return _built;
    }

    // A shape halfway between the two worlds. Both sides are written as the
    // same run of points (tools/atlas/gen_atlas.py resamples them), so the
    // change is one lerp per point.
    function morphPath(pair, t) {
        let d = "";
        for (let r = 0; r < pair.from.length; r++) {
            const a = pair.from[r], b = pair.to[r];
            const n = Math.min(a.length, b.length);
            for (let i = 0; i < n; i++) {
                const x = a[i][0] + (b[i][0] - a[i][0]) * t;
                const y = a[i][1] + (b[i][1] - a[i][1]) * t;
                d += (i ? "L" : "M") + x.toFixed(2) + " " + (-y).toFixed(2);
            }
            d += "Z";
        }
        return d;
    }

    // ── the century ─────────────────────────────────────────────────────────

    const FIRST_YEAR = 1900;

    // The year the party is living in. The atlas never reads past it: the map
    // is a record of what happened, not a forecast.
    function currentGameYear() {
        try {
            const TD = window.TimeDateSystem;
            if (TD && typeof TD.getCurrentDateObj === "function") {
                const y = TD.getCurrentDateObj().getFullYear();
                if (Number.isFinite(y)) return Math.max(FIRST_YEAR, y);
            }
        } catch (e) { /* the clock is not up yet */ }
        return 2001;
    }

    // How far through the change a year stands: 0 the world before, 1 the world
    // after, in between while the western hemisphere is being replaced.
    function eraProgress(year, era) {
        const from = era.legacyUntil, to = era.settledFrom;
        if (year <= from) return 0;
        if (year >= to) return 1;
        return (year - from) / (to - from);
    }

    // Who held a nation in a given year, read off the century the
    // HistorySimulator ran. A world that has never been simulated answers with
    // the country table, which is where it started.
    function controllerAt(country, year, cache) {
        const line = nationTimeline(country, cache);
        let held = null;
        for (let i = 0; i < line.length; i++) {
            if (line[i].year > year) break;
            held = line[i].controller;
        }
        if (held) return held;
        const entry = countryList().find((c) => c.country === country);
        return entry ? holderOf(entry) : NEUTRAL;
    }

    // Every time a nation changed hands, as [{year, controller}]. Read once per
    // nation per visit: the slider asks for this on every step.
    function nationTimeline(country, cache) {
        if (cache && cache[country]) return cache[country];
        let line = [];
        try {
            const HM = window.HistoryManager;
            const recs = (HM && HM.getNationHistory) ? HM.getNationHistory(country) : [];
            line = (recs || []).map((r) => ({
                year: parseInt(String(r.date).slice(0, 4), 10) || FIRST_YEAR,
                controller: r.controller || NEUTRAL,
                reason: r.reason || "",
            })).sort((a, b) => a.year - b.year);
        } catch (e) {
            line = [];
        }
        if (cache) cache[country] = line;
        return line;
    }

